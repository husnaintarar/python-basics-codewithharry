friends = ["apple", "banana", "cherry", 50, 100, 1.5, True, False]
print(friends)
friends.append("orange") # adds "orange" to the end of the list
print(friends)
friends.insert(1, "grape") # inserts "grape" at index 1
print(friends)  
friends.remove("banana") # removes "banana" from the list
print(friends)

numbers = [1, 2, 3, 9, 4, 8, 5, 7 ]
numbers.sort() # sorts the list in ascending order
print(numbers)
numbers.reverse() # reverses the order of the list
print(numbers)